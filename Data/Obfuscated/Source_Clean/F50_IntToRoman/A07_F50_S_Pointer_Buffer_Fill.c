void vH(int N13, char* D) {
    char *tj = D;
    while(N13 >= 1000) { *tj++ = 'M'; N13 -= 1000; }
    if(N13 >= 900) { *tj++ = 'C'; *tj++ = 'M'; N13 -= 900; }
    if(N13 >= 500) { *tj++ = 'D'; N13 -= 500; }
    if(N13 >= 400) { *tj++ = 'C'; *tj++ = 'D'; N13 -= 400; }
    while(N13 >= 100) { *tj++ = 'C'; N13 -= 100; }
    if(N13 >= 90) { *tj++ = 'X'; *tj++ = 'C'; N13 -= 90; }
    if(N13 >= 50) { *tj++ = 'L'; N13 -= 50; }
    if(N13 >= 40) { *tj++ = 'X'; *tj++ = 'L'; N13 -= 40; }
    while(N13 >= 10) { *tj++ = 'X'; N13 -= 10; }
    if(N13 >= 9) { *tj++ = 'I'; *tj++ = 'X'; N13 -= 9; }
    if(N13 >= 5) { *tj++ = 'V'; N13 -= 5; }
    if(N13 >= 4) { *tj++ = 'I'; *tj++ = 'V'; N13 -= 4; }
    while(N13 >= 1) { *tj++ = 'I'; N13 -= 1; }
    *tj = '\0';
}